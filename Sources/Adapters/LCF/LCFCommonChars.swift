//  GB18030（GBK 的超集）与 Big5 的常用字表 —— LCFTextCodec 在两者之间决胜用。
//
//  为什么需要这两张表：GB18030 与 Big5 的字节域几乎完全重叠
//  （GB18030 首字节 0x81–0xFE、尾字节 0x40–0xFE 除 0x7F；Big5 首字节 0xA1–0xF9、
//  尾字节 0x40–0x7E / 0xA1–0xFE），**任何合法 Big5 字节串都是合法 GB18030**。
//  所以字节范围判据不可能把繁体文本抢回来；而两者解出来的又都是汉字，
//  LCFTextCodec 里"汉字一律加分"的字符类打分同样分不出。
//  剩下的信号只有语义：**正确编码解出来的是人话，错误编码解出来的是生僻字**。
//  这两张表就是"人话"的尺子 —— 高频字命中率高的那个编码胜出。
//
//  表的来源与口径：
//   - 两表同源同序：同一份按字频降序排列的常用字表，GB 版取简体写法、Big5 版取繁体写法。
//     两表 1007 字重合，各自另有约 580 个本文字体独有的高频字 —— 这 580 个才是判别力来源。
//   - 收 1592 条（去重后 1590 / 1589）。实测 3300+ 条真实 Big5 字段
//     （Chi-Hsin/reversestone 3004 条 + RenaWevin 514 条）：1592 条的区分度明显好于 600 条
//     及以下的小表 —— 小表会让"生僻但正确的人名/技能名"两侧都得 0 分，平手就退回 GB18030。
//   - 表内只加分，表外**不扣分**（真实文本里的生僻字不该被当罪证）；扣分只给
//     "解错了才会出现"的字符（PUA / 半角片假名 / 西里尔），见 LCFTextCodec.commonness。
//   - 每个字都必须能被对应编码表示 —— lcf_probe 的 L17e 钉住这条，防止手改字表时混进
//     编不出来的字（那种字永远不会出现在解码结果里，只会白白稀释命中率）。
//
//  本文件只放数据；判定逻辑在 LCFTextCodec.detect。
//

